// ตัวแปรควบคุม
const menuContainer = document.getElementById('menuContainer');
const checkboxes = document.querySelectorAll('.checkbox-input');
const resultCount = document.getElementById('countValue');
const resetBtn = document.getElementById('resetBtn');
const backToTop = document.getElementById('backToTop');

// แสดงเมนูทั้งหมดตอนเริ่มต้น
renderMenu(menuData);

// กรองเมนูเมื่อมีการเปลี่ยนแปลงช่องทำเครื่องหมาย
checkboxes.forEach(checkbox => {
    checkbox.addEventListener('change', filterMenus);
});

// ปุ่มรีเซ็ต
resetBtn.addEventListener('click', () => {
    checkboxes.forEach(cb => cb.checked = false);
    filterMenus();
});

// ปุ่มกลับด้านบน
window.addEventListener('scroll', () => {
    if (window.scrollY > 300) {
        backToTop.classList.add('visible');
    } else {
        backToTop.classList.remove('visible');
    }
});

backToTop.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
});

// ฟังก์ชันกรองเมนู
function filterMenus() {
    const activeFilters = Array.from(checkboxes)
        .filter(cb => cb.checked)
        .map(cb => cb.dataset.filter);
    
    let filteredMenu;
    if (activeFilters.length === 0) {
        filteredMenu = menuData;
    } else {
        filteredMenu = menuData.filter(menu => 
            activeFilters.some(filter => menu.tags.includes(filter))
        );
    }
    
    renderMenu(filteredMenu);
}

// ฟังก์ชันแสดงรายการเมนู
function renderMenu(menus) {
    menuContainer.innerHTML = '';
    
    if (menus.length === 0) {
        menuContainer.innerHTML = `
            <div class="no-result">
                😥 ไม่พบเมนูที่ตรงกับเงื่อนไข<br>
                ลองเลือกประเภทอื่นดูนะครับ
            </div>
        `;
        resultCount.textContent = '0';
        return;
    }
    
    resultCount.textContent = menus.length;
    
    menus.forEach((menu, index) => {
        const card = document.createElement('div');
        card.className = 'menu-card';
        card.style.animationDelay = `${index * 0.1}s`;
        
        const tagsHTML = menu.tagNames.map(tag => 
            `<span class="tag">${tag}</span>`
        ).join('');
        
        card.innerHTML = `
            <div class="menu-header">
                <h3 class="menu-name">${menu.name}</h3>
                <div class="menu-tags">${tagsHTML}</div>
            </div>
            <div class="menu-body">
                <p class="menu-desc">${menu.desc}</p>
                <button class="toggle-btn" data-id="${menu.id}">📖 ดูวิธีทำ ▼</button>
                <div class="hidden-content" id="content-${menu.id}">
                    <div class="ingredients">
                        <h4>🥬 วัตถุดิบ</h4>
                        <ul>
                            ${menu.ingredients.map(i => `<li>${i}</li>`).join('')}
                        </ul>
                    </div>
                    <div class="steps">
                        <h4>👩‍🍳 วิธีทำ</h4>
                        <p>${menu.steps.replace(/\n/g, '<br>')}</p>
                    </div>
                </div>
            </div>
        `;
        
        menuContainer.appendChild(card);
        
        // แสดงการ์ดพร้อมแอนิเมชัน
        setTimeout(() => {
            card.classList.add('show');
        }, index * 80);
    });
    
    // เพิ่มฟังก์ชันปุ่มแสดง/ซ่อนวิธีทำ
    document.querySelectorAll('.toggle-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const id = btn.dataset.id;
            const content = document.getElementById(`content-${id}`);
            content.classList.toggle('expanded');
            btn.textContent = content.classList.contains('expanded') 
                ? '📖 ซ่อนวิธีทำ ▲' 
                : '📖 ดูวิธีทำ ▼';
        });
    });
}
